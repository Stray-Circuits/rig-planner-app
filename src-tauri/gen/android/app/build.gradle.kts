val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

// Release signing config — loaded from key.properties at the android gen root.
// File is gitignored; absence is fine (debug builds don't need it, and release
// builds will fall through to unsigned with a clear Gradle warning).
val keystoreProperties = Properties().apply {
    val propFile = rootProject.file("key.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

android {
    compileSdk = 36
    namespace = "com.straycircuits.rigplanner"
    defaultConfig {
        manifestPlaceholders["usesCleartextTraffic"] = "false"
        applicationId = "com.straycircuits.rigplanner"
        minSdk = 24
        targetSdk = 36
        // versionName is the semver string Tauri syncs from tauri.conf.json
        // (which itself reads from package.json). versionCode is derived from
        // it via MAJOR*10000 + MINOR*100 + PATCH so we never hand-manage two
        // numbers — the autogenerated tauri.android.versionCode is ignored.
        // Formula caps each component at 99 (well past anything we'll ship).
        val resolvedVersionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")
        val semverCore = resolvedVersionName.substringBefore("-").split(".")
        versionCode = if (semverCore.size >= 3) {
            val major = semverCore[0].toIntOrNull() ?: 0
            val minor = semverCore[1].toIntOrNull() ?: 0
            val patch = semverCore[2].toIntOrNull() ?: 0
            major * 10_000 + minor * 100 + patch
        } else 1
        versionName = resolvedVersionName
    }
    signingConfigs {
        create("release") {
            val storeFilePath = keystoreProperties.getProperty("storeFile")
            if (storeFilePath != null) {
                storeFile = file(storeFilePath)
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }
    buildTypes {
        getByName("debug") {
            manifestPlaceholders["usesCleartextTraffic"] = "true"
        }
        getByName("release") {
            if (keystoreProperties.getProperty("storeFile") != null) {
                signingConfig = signingConfigs.getByName("release")
            }
            isMinifyEnabled = true
            proguardFiles(
                *fileTree(".") { include("**/*.pro") }
                    .plus(getDefaultProguardFile("proguard-android-optimize.txt"))
                    .toList().toTypedArray()
            )
        }
    }
    kotlinOptions {
        jvmTarget = "1.8"
    }
    buildFeatures {
        buildConfig = true
    }
}

